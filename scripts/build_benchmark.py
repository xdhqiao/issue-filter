def main():
    rows = []
    for category, expected_id, expected_candidates, descriptions in GROUPS:
        for description in descriptions:
            rows.append({
                "case_id": f"case_{len(rows) + 1:03d}",
                "category": category,
                "description": description,
                "expected_id": expected_id,
                "expected_candidate_ids": expected_candidates,
            })
    assert len(rows) == 120
    assert len({row["description"] for row in rows}) == len(rows)
    assert sum(row["expected_id"] is not None for row in rows) == 60
    path = Path("data/benchmark.v1.jsonl")
    path.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows), encoding="utf-8")
    print(f"Wrote {len(rows)} cases to {path}; positives=60, negatives=60")


if __name__ == "__main__":
    main()
